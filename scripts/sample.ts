// Builds the sample (templates/_shared/example.ts and docs/umami.json) from Umami's real schema files.
// Run: node --experimental-strip-types scripts/sample.ts
import { readFileSync, writeFileSync } from "node:fs";
import { parseSchema } from "../templates/_shared/schema.ts";
import { toValues } from "../templates/_shared/values.ts";

const read = (f: string) => parseSchema(readFileSync(new URL(`../public/samples/${f}`, import.meta.url), "utf8"));
// Notes a team would write; ours, from the schema's own names and defaults.
const notes = {
  website: "A site being tracked. Sessions, events and reports belong to a website.",
  session: "One visitor's session on a website, with the browser, OS, device, screen, language and location seen.",
  website_event: "One page view or custom event in a session.",
  "website_event.event_type": "1 by default (a page view).",
  error_issue: "Browser errors grouped by fingerprint, so the same error is one issue.",
  "error_issue.status": "Starts as \"unresolved\".",
  error_event: "One browser error as it happened: message, stack, page, release and device.",
};
const values = toValues(read("umami-v3.5.0.prisma"), { project: "Umami", version: "v3.5.0", source: "prisma/schema.prisma", date: "2026-11-19", owner: "Platform team, Northwind Labs" }, notes, {
  schema: read("umami-v3.4.1.prisma"),
  version: "v3.4.1",
});
const json = JSON.stringify(values, null, 2);
writeFileSync(new URL("../docs/umami.json", import.meta.url), `${json}\n`);
writeFileSync(
  new URL("../templates/_shared/example.ts", import.meta.url),
  `// The sample: Umami's real Prisma schema (github.com/umami-software/umami, MIT) at v3.5.0, compared with v3.4.1.\n// Generated by scripts/sample.ts. The notes and "Northwind Labs" are ours.\nconst example = ${json};\n\nexport default example;\n`,
);
console.log(values.tables.length, "tables;", values.changes.length, "changes");
